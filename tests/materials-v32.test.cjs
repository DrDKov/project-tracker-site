const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const rich=read('assets/materials-rich-editor.js');
const ui=read('assets/materials-v32.js');
const loader=read('assets/app.js');
const html=read('index.html');
const sql=read('supabase/migrations/20261013_materials_v32_collaboration_history.sql');
const css=read('assets/app.css');
new vm.Script(rich);
new vm.Script(ui);
const window={};
vm.runInNewContext(rich,{window,Event:class {}});
const m=window.ProjectTrackerMaterialsRich;
assert.ok(m,'Markdown editor exported');
const source='# Инструкция\n\n**Важно**: *сегодня*\n\n- [ ] Перезвонить\n- [x] Записать\n\n| Этап | Ответственный |\n| --- | --- |\n| Звонок | Сотрудник |\n\n[Документ](https://example.com)';
const preview=m.render(source);
assert.match(preview,/<h1>Инструкция<\/h1>/);
assert.match(preview,/<strong>Важно<\/strong>/);
assert.match(preview,/<em>сегодня<\/em>/);
assert.match(preview,/<input type="checkbox" data-library-check-line="4" /);
assert.match(preview,/<table>/);
assert.match(preview,/<th>Этап<\/th>/);
assert.match(preview,/<a href="https:\/\/example.com"/);
assert.equal(m.toggle(source,4,true).split('\n')[4],'- [x] Перезвонить');
assert.equal(m.toggle(source,5,false).split('\n')[5],'- [ ] Записать');
const escaped=m.render('<img src=x onerror="alert(1)">\n\n[evil](javascript:alert(1))');
assert.doesNotMatch(escaped,/<img|href="javascript:/);
assert.match(escaped,/&lt;img/);
assert.ok(m.toolbar().includes('data-library-format="table"'));
assert.ok(m.toolbar().includes('data-library-format="check"'));
assert.match(loader,/materials-rich-editor\.js\?v=20261013-materials-v32-v1/);
assert.match(loader,/materials-v32\.js\?v=20261013-materials-v32-v1/);
assert.doesNotMatch(loader,/\.\/materials-v3\.js\?/);
assert.match(html,/app\.js\?v=20261013-mobile-task-controls-v1/);
assert.match(html,/app\.css\?v=20261013-materials-v32-v1/);
for(const section of ['Версия','Корзина','Восстановить','Редакторы материала','Создать задачу по шаблону','Чек-лист'])assert.ok(ui.includes(section)||rich.includes(section),section);
for(const name of ['library_save_revision','library_save_file_metadata','library_restore_revision','library_replace_file','library_set_trashed','library_create_workflow_task','library_access','library_versions'])assert.ok(ui.includes(name),name);
assert.match(ui,/p_expected_version:m\.version_number/);
assert.match(ui,/data-library-check-line/);
assert.match(ui,/function guardDirty/);
assert.match(ui,/S\.formDirty/,'Unsaved changes are guarded');
assert.match(sql,/create table if not exists public\.library_versions/);
assert.match(sql,/create table if not exists public\.library_access/);
assert.match(sql,/create trigger library_revision_guard/);
assert.match(sql,/on conflict\(material_id,version_number\) do nothing/);
assert.match(sql,/create or replace function public\.library_create_workflow_task/);
assert.match(sql,/library_can_edit_id/);
assert.match(sql,/library_user_project_access/);
assert.match(sql,/Revision conflict/);
assert.match(sql,/version_number=version_number\+1/);
assert.match(sql,/created_at timestamptz not null default now/);
assert.match(css,/\.library-rich-toolbar/);
assert.match(css,/\.library-version-row/);
console.log('Materials 3.2 Markdown formatting, table, checklist, XSS, revisions, ACL and cache tests passed');
