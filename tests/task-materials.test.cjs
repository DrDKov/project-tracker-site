const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const script=read('assets/task-materials.js');
const threads=read('assets/task-comment-threads.js');
const runtime=read('assets/app-runtime.js');
const lib=read('assets/materials-v3.js');
const html=read('index.html');
const loader=read('assets/app.js');
const css=read('assets/task-inspector.css');
const sql=read('supabase/migrations/20261013_task_material_links.sql');
new vm.Script(script,{filename:'task-materials.js'});
new vm.Script(threads,{filename:'task-comment-threads.js'});
new vm.Script(lib,{filename:'materials-v3.js'});
assert.match(loader,/task-materials\.js\?v=20261013-comment-composer-fix-v1/);
assert.match(loader,/materials-v3\.js\?v=20261013-comment-composer-fix-v1/);
assert.match(html,/task-comment-threads\.js\?v=20261013-comment-composer-fix-v1/);
assert.match(html,/task-inspector\.css\?v=20261013-comment-composer-fix-v1/);
assert.match(runtime,/ProjectTrackerTaskMaterials\?\.onTaskOpen\(id,/);
assert.match(sql,/create table if not exists public\.task_material_links/);
assert.match(sql,/constraint task_material_links_unique unique\(task_id,material_id\)/);
assert.match(sql,/alter table public\.task_material_links enable row level security/);
assert.match(sql,/task_material_links_read/);
assert.match(sql,/task_material_links_add/);
assert.match(sql,/task_material_links_remove/);
assert.match(sql,/m\.scope='team'/);
assert.match(sql,/m\.scope='project' and m\.project_id=t\.project_id/);
assert.doesNotMatch(sql,/m\.scope='personal'/,'Private documents must never auto-share via a task link');
assert.match(sql,/library_can_read_id\(material_id\)/);
assert.match(script,/\.from\('workspace_library'\)\.select/);
assert.match(script,/\.from\('task_material_links'\)\.insert/);
assert.match(script,/\.from\('task_material_links'\)\.delete/);
assert.match(script,/function insertComment\(content\)/);
assert.match(script,/field\.setRangeText\(addition,at,field\.selectionEnd\?\?at,'end'\)/);
assert.match(script,/function openCommentLink\(id\)/);
assert.match(script,/function previewMaterial\(id\)/);
assert.match(script,/\.createSignedUrl\(item\.storage_path,300\)/);
assert.match(lib,/async function openMaterialById\(id\)/);
assert.match(lib,/window\.addEventListener\('hashchange',handleMaterialHash\)/);
assert.match(css,/\.task-material-picker\{/);
assert.match(css,/\.task-comment-material-link\{/);

const state={projectId:'proj-a'};
const match=script.match(/const canUseForTask=m=>[^;]+;/);
assert.ok(match,'access filter present');
const context=vm.createContext({state});
vm.runInContext(match[0].replace(/^const /,'var '),context);
const eligible=context.canUseForTask;
assert.equal(eligible({scope:'team'}),true);
assert.equal(eligible({scope:'project',project_id:'proj-a'}),true);
assert.equal(eligible({scope:'project',project_id:'proj-b'}),false);
assert.equal(eligible({scope:'personal',project_id:null}),false);
const format=threads.slice(threads.indexOf('function commentBodyWithMaterials('),threads.indexOf('function renderThreadCard('));
assert.ok(format.startsWith('function'));
const c=vm.createContext({});
vm.runInContext(format,c);
const esc=x=>String(x).replace(/[&<>"]/g,y=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[y]));
const id='123e4567-e89b-42d3-a456-426614174000';
const formatted=c.commentBodyWithMaterials('Материал: тест\nhttps://drdkov.github.io/project-tracker-site/#materials/'+id,esc);
assert.match(formatted,/data-library-open="123e4567-e89b-42d3-a456-426614174000"/);
assert.doesNotMatch(formatted,/<a href=/,'Internal material links use scoped preview, not direct unauthenticated URLs');
const dangerous=c.commentBodyWithMaterials('<img src=x onerror=alert(1)>',esc);
assert.doesNotMatch(dangerous,/<img/);
assert.match(dangerous,/&lt;img/);
const outside=c.commentBodyWithMaterials('https://evil.example/#materials/'+id,esc);
assert.doesNotMatch(outside,/data-library-open/);
console.log('Task material access, deep links, attachment RLS, comment insertion and XSS checks passed');
